"""Evaluation metrics for SQL generation quality.

Implements the official BIRD-Interact Success Rate (SR) metric and exposes
reusable helpers for executing SQL against SQLite databases.  The execution
logic is intentionally decoupled so that the pipeline tools can import and
reuse it without duplicating code.
"""

from __future__ import annotations

import sqlite3
from abc import ABC, abstractmethod
from typing import Any


class BaseSuccessCriterion(ABC):
    """Abstract base class for SQL evaluation criteria."""

    @abstractmethod
    def evaluate(
        self,
        predicted_sql: str,
        ground_truth_sql: str,
        database_path: str,
    ) -> bool:
        """Evaluate whether a predicted SQL meets the success criterion.

        Args:
            predicted_sql: The SQL query generated by the model.
            ground_truth_sql: The reference (gold) SQL query.
            database_path: Filesystem path to the SQLite database.

        Returns:
            ``True`` if the predicted query satisfies the criterion.
        """


# ---------------------------------------------------------------------------
# Reusable database helpers
# ---------------------------------------------------------------------------


def execute_sql(sql: str, database_path: str) -> list[tuple[Any, ...]]:
    """Execute a SQL query on an SQLite database and return all result rows.

    Args:
        sql: SQL query string.
        database_path: Filesystem path to the SQLite database.

    Returns:
        A list of tuples, one per result row.

    Raises:
        sqlite3.Error: If the query fails to execute.
    """
    conn = sqlite3.connect(database_path)
    try:
        cursor = conn.execute(sql)
        return cursor.fetchall()
    finally:
        conn.close()


def result_sets_match(
    predicted_sql: str,
    ground_truth_sql: str,
    database_path: str,
) -> bool:
    """Check whether two SQL queries produce identical result sets.

    Both queries are executed against the same SQLite database and their
    result rows (as sets of tuples) are compared.

    Args:
        predicted_sql: The SQL query generated by the model.
        ground_truth_sql: The reference (gold) SQL query.
        database_path: Filesystem path to the SQLite database.

    Returns:
        ``True`` if the two result sets are equal, ``False`` otherwise
        (including when either query raises an error).
    """
    try:
        predicted_results = set(execute_sql(predicted_sql, database_path))
        ground_truth_results = set(execute_sql(ground_truth_sql, database_path))
        return predicted_results == ground_truth_results
    except sqlite3.Error:
        return False


# ---------------------------------------------------------------------------
# Concrete metric
# ---------------------------------------------------------------------------


class SuccessRate(BaseSuccessCriterion):
    """Official BIRD-Interact Success Rate metric.

    A predicted SQL is considered successful if executing it on the target
    SQLite database yields the exact same result set as the ground-truth
    query.
    """

    def evaluate(
        self,
        predicted_sql: str,
        ground_truth_sql: str,
        database_path: str,
    ) -> bool:
        """Return ``True`` when the predicted and gold queries match.

        Args:
            predicted_sql: The SQL query generated by the model.
            ground_truth_sql: The reference (gold) SQL query.
            database_path: Filesystem path to the SQLite database.

        Returns:
            ``True`` if the result sets are identical.
        """
        return result_sets_match(predicted_sql, ground_truth_sql, database_path)
